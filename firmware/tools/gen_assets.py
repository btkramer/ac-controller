#!/usr/bin/env python3
"""Regenerate src/assets/*.c: mode-colored conic gradient rings for the dial (RGB565) and one
alpha-only glow (A8, recolored per mode at runtime). Run from firmware/: python3 tools/gen_assets.py"""
import math, random

RING = 300  # dial size in px; must match the arc object size in ui.cpp
GLOW = 400
# mode -> (start color at 61F, end color at 88F); keep in sync with theme.h
RINGS = {
    "cool": ("5fe1ff", "2f6bff"), "heat": ("ffc24a", "ff4d2e"), "auto": ("7af0b0", "14b8a6"),
    "fan": ("c9bcff", "7b61ff"), "dry": ("8ff3ff", "1497c7"),
}

def rgb(h): return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))

def emit(name, cf, w, h, stride, data, out):
    out.write(f"static const uint8_t {name}_map[] = {{\n")
    for i in range(0, len(data), 24):
        out.write("  " + ",".join(str(b) for b in data[i:i + 24]) + ",\n")
    out.write("};\n")
    out.write(f"const lv_image_dsc_t {name} = {{\n  .header = {{ .magic = LV_IMAGE_HEADER_MAGIC, .cf = {cf}, .flags = 0, "
              f".w = {w}, .h = {h}, .stride = {stride} }},\n  .data_size = sizeof({name}_map),\n  .data = {name}_map,\n}};\n\n")

with open("src/assets/assets.c", "w") as out:
    out.write("// Generated by tools/gen_assets.py\n#include <lvgl.h>\n\n")
    random.seed(1)
    c = RING / 2
    for mode, (a, b) in RINGS.items():
        ca, cb = rgb(a), rgb(b)
        data = bytearray()
        for y in range(RING):
            for x in range(RING):
                ang = math.degrees(math.atan2(y + .5 - c, x + .5 - c)) % 360  # 0 = east, clockwise on screen
                t = ((ang - 135) % 360) / 270
                t = min(max(t, 0), 1)
                r, g, bl = (ca[i] + (cb[i] - ca[i]) * t for i in range(3))
                v = ((int(r) >> 3) << 11) | ((int(g) >> 2) << 5) | (int(bl) >> 3)
                data += bytes((v & 0xFF, v >> 8))
        emit(f"img_ring_{mode}", "LV_COLOR_FORMAT_RGB565", RING, RING, RING * 2, data, out)
    # radial glow: strong core fading to nothing, with light dithering against RGB565 banding
    g = GLOW / 2
    data = bytearray()
    for y in range(GLOW):
        for x in range(GLOW):
            d = math.hypot(x + .5 - g, y + .5 - g) / g
            if d >= 1: a = 0
            elif d < .55: a = .46 + (.12 - .46) * (d / .55)
            else: a = .12 * (1 - (d - .55) / .45) ** 1.6
            v = a * 255 + random.uniform(-1.5, 1.5)
            data.append(max(0, min(255, int(round(v)))))
    emit("img_glow", "LV_COLOR_FORMAT_A8", GLOW, GLOW, GLOW, data, out)

with open("src/assets/assets.h", "w") as h:
    h.write("// Generated by tools/gen_assets.py\n#pragma once\n#include <lvgl.h>\n\n")
    for mode in RINGS: h.write(f"LV_IMAGE_DECLARE(img_ring_{mode});\n")
    h.write("LV_IMAGE_DECLARE(img_glow);\n")
print("assets ok")
