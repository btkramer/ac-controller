#!/usr/bin/env python3
"""Regenerate src/fonts/*.c with lv_font_conv (npx). Run from firmware/: python3 tools/gen_fonts.py
Sources in tools/fontsrc: Outfit and Montserrat static instances (Google Fonts, OFL), Font Awesome 5.15.4 solid (OFL)."""
import subprocess, os
SRC = "tools/fontsrc"
OUT = "src/fonts"
# Font Awesome 5 solid glyphs used by the UI: name -> codepoint
ICONS = {
    "POWER": 0xF011, "COOL": 0xF2DC, "HEAT": 0xF06D, "AUTO": 0xF2F1, "FAN": 0xF863, "DRY": 0xF043,
    "SUN": 0xF185, "MOON": 0xF186, "CLOUD": 0xF0C2, "CLOUD_SUN": 0xF6C4, "CLOUD_MOON": 0xF6C3, "RAIN": 0xF73D,
    "LINK": 0xF0C1, "COG": 0xF013, "WIFI": 0xF1EB, "TIMER": 0xF252, "CAL": 0xF073, "WARN": 0xF071,
    "AIR": 0xF72E, "VSWING": 0xF338, "HSWING": 0xF337, "BED": 0xF236, "COUCH": 0xF4B8, "CHECK": 0xF00C,
    "CLOSE": 0xF00D, "BACK": 0xF053, "MINUS": 0xF068, "PLUS": 0xF067,
}
ICON_RANGE = ",".join(hex(c) for c in ICONS.values())
TEXT = "0x20-0x7E,0xB0,0xB7,0x2212,0x2026,0x2013"
DIGITS = "0x20,0x2D,0x2E,0x30-0x3A,0xB0"

FONTS = [  # name, size, [(ttf, range), ...]
    ("ui14", 14, [("Montserrat-Medium.ttf", TEXT), ("fa-solid-900.ttf", ICON_RANGE)]),
    ("ui16", 16, [("Montserrat-Medium.ttf", TEXT), ("fa-solid-900.ttf", ICON_RANGE)]),
    ("ui18", 18, [("Montserrat-Medium.ttf", TEXT), ("fa-solid-900.ttf", ICON_RANGE)]),
    ("ui20", 20, [("Montserrat-Medium.ttf", TEXT), ("fa-solid-900.ttf", ICON_RANGE)]),
    ("ui22", 22, [("Montserrat-SemiBold.ttf", TEXT), ("fa-solid-900.ttf", ICON_RANGE)]),
    ("icon28", 28, [("fa-solid-900.ttf", ICON_RANGE)]),
    ("o26", 26, [("Outfit-Light.ttf", TEXT)]),
    ("o34", 34, [("Outfit-Light.ttf", TEXT)]),
    ("n40", 40, [("Outfit-ExtraLight.ttf", DIGITS)]),
    ("n54", 54, [("Outfit-ExtraLight.ttf", DIGITS)]),
    ("n76", 76, [("Outfit-ExtraLight.ttf", DIGITS)]),
    ("n112", 112, [("Outfit-ExtraLight.ttf", DIGITS)]),
    ("n150", 150, [("Outfit-ExtraLight.ttf", DIGITS)]),
]

os.makedirs(OUT, exist_ok=True)
for name, size, parts in FONTS:
    cmd = ["npx", "-y", "lv_font_conv@1.5.2", "--no-compress", "--bpp", "4", "--size", str(size),
           "--format", "lvgl", "--lv-include", "lvgl.h", "-o", f"{OUT}/font_{name}.c"]
    for ttf, rng in parts:
        cmd += ["--font", f"{SRC}/{ttf}", "-r", rng]
    subprocess.run(cmd, check=True)

with open(f"{OUT}/fonts.h", "w") as f:
    f.write("// Generated by tools/gen_fonts.py\n#pragma once\n#include <lvgl.h>\n\n")
    for name, _, _ in FONTS:
        f.write(f"LV_FONT_DECLARE(font_{name});\n")
    f.write("\n")
    for k, cp in ICONS.items():
        b = chr(cp).encode("utf-8")
        f.write(f'#define IC_{k} "' + "".join(f"\\x{x:02X}" for x in b) + '"\n')
print("fonts ok")
